export const ALL_REGIMENTS: Regiment[] = [...UNION_REGIMENTS, ...CONFEDERATE_REGIMENTS];

export function regimentsForFaction(faction: Faction): Regiment[] {
  return ALL_REGIMENTS.filter((r) => r.faction === faction);
}

export function regimentById(id: string): Regiment | undefined {
  return ALL_REGIMENTS.find((r) => r.id === id);
}

